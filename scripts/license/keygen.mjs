/**
 * Vendor-only, run once on your own PC: creates the Ed25519 license signing key.
 * The private key stays on your PC; only the public key is built into the app.
 *
 * Usage: node scripts/license/keygen.mjs [--force]
 */
import { generateKeyPairSync } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const keyDir = process.env.LEDGER_VENDOR_DIR ?? path.join(os.homedir(), ".ledger-vendor");
const privatePath = path.join(keyDir, "license-signing-key.pem");
const publicTs = path.join(root, "apps/api/src/license-key.ts");

if (fs.existsSync(privatePath) && !process.argv.includes("--force")) {
  console.error(`Signing key already exists: ${privatePath}`);
  console.error("Replacing it invalidates every license already issued. Pass --force to do it anyway.");
  process.exit(1);
}

const { publicKey, privateKey } = generateKeyPairSync("ed25519");
fs.mkdirSync(keyDir, { recursive: true, mode: 0o700 });
fs.writeFileSync(privatePath, privateKey.export({ type: "pkcs8", format: "pem" }), { mode: 0o600 });

const pem = publicKey.export({ type: "spki", format: "pem" }).toString().trim();
fs.writeFileSync(
  publicTs,
  `/** Ed25519 public key for verifying license files. Generated by scripts/license/keygen.mjs. */\nexport const LICENSE_PUBLIC_KEY_PEM = \`${pem}\`;\n`,
);

console.log(`Private signing key: ${privatePath}`);
console.log("Back this file up somewhere safe. Anyone holding it can issue licenses.");
console.log(`Public key written to ${path.relative(root, publicTs)}`);
